"""Generate TS contracts and compile-time examples from Pydantic + shared JSON.

Run from any directory: python scripts/generate_simulation_types.py [--check].
No API/schema generation dependencies; legacy models are included only when referenced.
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from src.contracts import simulation  # noqa: E402

MODELS = [
    simulation.CameraScan,
    simulation.LidarMeasurement,
    simulation.LightMeasurement,
    simulation.PoseMeasurement,
    simulation.SimulationConfig,
    simulation.ScenarioDefinition,
    simulation.SimulationStatus,
    simulation.SimulationSnapshot,
    simulation.SimulationControl,
    simulation.ObservationSample,
    simulation.TemporalObservationQuery,
]
HEADER = "// Generated by scripts/generate_simulation_types.py; do not edit.\n"


def ts_type(schema: dict) -> str:
    """Translate only JSON Schema constructs used by these contracts; fail on new ones."""
    if not schema:
        return "unknown"
    if "$ref" in schema:
        return schema["$ref"].rsplit("/", 1)[1]
    if "const" in schema:
        return json.dumps(schema["const"])
    if "enum" in schema:
        return " | ".join(json.dumps(value) for value in schema["enum"])
    if "anyOf" in schema:
        return " | ".join(ts_type(part) for part in schema["anyOf"])
    if "oneOf" in schema:
        return " | ".join(ts_type(part) for part in schema["oneOf"])
    kind = schema.get("type")
    if kind == "object":
        if "properties" not in schema:
            extra = schema.get("additionalProperties", {})
            return "Record<string, " + (ts_type(extra) if extra else "unknown") + ">"
        required = schema.get("required", [])
        fields = [
            f"  {json.dumps(name)}{'' if name in required else '?'}: {ts_type(value)};"
            for name, value in schema["properties"].items()
        ]
        return "{\n" + "\n".join(fields) + "\n}"
    if kind == "array":
        return f"Array<{ts_type(schema['items'])}>"
    if kind in ("number", "integer"):
        return "number"
    if kind in ("string", "boolean", "null"):
        return kind
    raise ValueError(f"Unsupported schema construct: {schema}")


def generated_files() -> dict[Path, str]:
    definitions = {}
    for model in MODELS:
        schema = model.model_json_schema()
        definitions.update(schema.pop("$defs", {}))
        definitions[model.__name__] = schema
    types = (
        HEADER + "// Numeric bounds, UTC, ordering and cross-field rules are checked in Python.\n\n"
    )
    types += (
        "\n\n".join(
            f"export type {name} = {ts_type(schema)};"
            for name, schema in sorted(definitions.items())
        )
        + "\n"
    )
    fixtures = json.loads((ROOT / "tests/fixtures/phase_two/contracts.json").read_text())
    fixture_type = {
        "configurations": "SimulationConfig[]",
        "scenario": "ScenarioDefinition",
        "statuses": "SimulationStatus[]",
        "snapshots": "SimulationSnapshot[]",
        "samples": "ObservationSample[]",
        "camera_scans": "CameraScan[]",
        "queries": "TemporalObservationQuery[]",
        "controls": "SimulationControl[]",
    }
    imports = ", ".join(sorted(set(value.rstrip("[]") for value in fixture_type.values())))
    examples = HEADER + f'import type {{ {imports} }} from "./simulationTypes";\n\n'
    examples += "export const validSimulationFixtures = "
    examples += json.dumps(fixtures["valid"], indent=2)
    examples += (
        " satisfies {\n"
        + "\n".join(f"  {key}: {value};" for key, value in fixture_type.items())
        + "\n};\n"
    )
    return {
        ROOT / "frontend/src/simulationTypes.ts": types,
        ROOT / "frontend/src/simulationFixtures.ts": examples,
    }


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    for path, content in generated_files().items():
        if args.check:
            if not path.exists() or path.read_text() != content:
                raise SystemExit(f"Outdated generated file: {path.relative_to(ROOT)}")
        else:
            path.write_text(content)
    print(
        "Simulation TypeScript contracts/fixtures " + ("verified." if args.check else "generated.")
    )


if __name__ == "__main__":
    main()
